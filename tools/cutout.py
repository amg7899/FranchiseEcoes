#!/usr/bin/env python3
"""Cuts a product picture out of its white background (the product cards on Home).

  python3 tools/cutout.py <picture.png> <name> [width ...]

Writes assets/img/v2/cut-<name>-<width>.webp for each width (default: the picture's width, capped
at 1600, and 640). The white background becomes transparent by colour-to-alpha: the soft shadow
under the product stays as translucent black, light greys inside the product stay opaque (only the
background connected to the picture's border is removed). The result is cropped to the product.
Needs Pillow and numpy. Afterwards embed the provenance:
  .claude/skills/impeccable/scripts/impeccable embed-prompt <file> --prompt "Generated by …"
"""
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'assets', 'img', 'v2')


def cutout(path, threshold=205, max_saturation=26):
    a = np.asarray(Image.open(path).convert('RGB')).astype(float)
    lightness = a.min(2)
    saturation = a.max(2) - a.min(2)
    # background = light, grey-ish pixels connected to the border
    candidate = Image.fromarray(np.where((lightness >= threshold) & (saturation < max_saturation), 255, 0).astype(np.uint8))
    candidate = ImageOps.expand(candidate, 1, fill=255)
    ImageDraw.floodfill(candidate, (0, 0), 128)
    background = np.asarray(candidate)[1:-1, 1:-1] == 128
    edge = background.copy()                      # the background plus a 2 px ring into the product
    for _ in range(2):
        grown = edge.copy()
        for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            grown |= np.roll(np.roll(edge, dy, 0), dx, 1)
        edge = grown
    distance = (255 - a).max(2) / 255.0            # how far from white
    alpha = np.ones(lightness.shape)
    alpha[edge] = distance[edge]
    shadow = background & (distance < 0.4)
    alpha[shadow] = np.clip((distance[shadow] - 0.05) * 1.5, 0, 1)
    safe = np.maximum(alpha, 1e-3)[..., None]
    rgb = a.copy()
    rgb[edge] = np.clip(255 - (255 - a[edge]) / safe[edge], 0, 255)   # un-premultiply against white
    out = Image.fromarray(np.dstack([rgb, alpha * 255]).astype(np.uint8), 'RGBA')
    return out.crop(out.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox())


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    picture, name = argv[1], argv[2]
    product = cutout(picture)
    widths = [int(w) for w in argv[3:]] or sorted({min(product.width, 1600), 640})
    os.makedirs(OUT, exist_ok=True)
    for w in widths:
        r = product if w >= product.width else product.resize((w, round(product.height * w / product.width)), Image.LANCZOS)
        target = os.path.join(OUT, f'cut-{name}-{r.width}.webp')
        r.save(target, 'WEBP', quality=86, method=6)
        print(os.path.relpath(target), r.size)


if __name__ == '__main__':
    main(sys.argv)
